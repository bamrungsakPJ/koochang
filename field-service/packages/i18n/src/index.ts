export const catalogs = { th, en };
export type TranslationKey = keyof Catalog;
/** Translate a key; {name} placeholders are filled from params. */
export function translate(language: Language, key: TranslationKey, params?: Record<string, string | number>): string {
  const text = catalogs[language][key];
  return params ? text.replace(/\{(\w+)\}/g, (match, name: string) => name in params ? String(params[name]) : match) : text;
}
export function errorMessage(language: Language, code: string): string {
  return code in th ? translate(language, code as TranslationKey) : translate(language, 'INTERNAL_ERROR');
}
export function formatMoney(amountMinor: number, language: Language): string {
  if (!Number.isSafeInteger(amountMinor) || amountMinor < 0) throw new RangeError('Invalid minor amount');
  return new Intl.NumberFormat(language === 'th' ? 'th-TH' : 'en-GB', { style: 'currency', currency: 'THB', currencyDisplay: 'code' }).format(amountMinor / 100);
}
export function formatDate(date: Date, language: Language, timeZone = 'Asia/Bangkok'): string {
  return new Intl.DateTimeFormat(language === 'th' ? 'th-TH-u-ca-buddhist-nu-latn' : 'en-GB-u-ca-gregory-nu-latn', {
    timeZone, day: 'numeric', month: 'long', year: 'numeric',
  }).format(date);
}
